#!/usr/bin/env python3
"""Promote the shared DIRECT-SCAN LUT into styles/ and generate presets-scans.js.

与 build-shared-prints.py 同构(2026-09-22 下午,数据见 validation/shared-lut/
docs/shared-lut-design.md):基准胶卷 Velvia 100(色域最宽当容器,自身恒等),
provia/ektachrome/kodachrome 经 3x20 三次预变换 W(钳位感知拟合)映射进表。
A/B 四款全 PASS(mae<=0.53 p99<=1.97,门 mae<=1 p99<=4 max<=12),且根治反转片
双重 DIR(现状逐款表同探针 p99 33-43)。

本脚本:
1. scan-fujifilm_velvia_100-41.png 从 validation/shared-lut/luts/ 复制进 styles/luts/
2. 从 pretransforms-scan.json 取三款胶卷的 cubic20 W,键=style id(velvia 恒等省略)
3. 按 stamp-mobile-lut-hashes.py 同款口径打 decoded-value FNV-1a hash
"""
import importlib, json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
b = importlib.import_module('bake-film-stocks')

SRC = ROOT / 'validation/shared-lut/luts'
DST = ROOT / 'styles/luts'
OUT = ROOT / 'styles/presets-scans.js'

SIZE = 41
REF_FILM = 'fujifilm_velvia_100'
TABLE = f'scan-{REF_FILM}-{SIZE}.png'
# style id -> upstream profile(velvia=基准恒等,不在 W 里)
FILMS = {'velvia': 'fujifilm_velvia_100', 'provia': 'fujifilm_provia_100f',
         'ektachrome': 'kodak_ektachrome_100', 'kodachrome': 'kodak_kodachrome_64'}


def fnv1a32(data: bytes) -> int:
    h = 0x811C9DC5
    for byte in data:
        h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    fits = json.loads((ROOT / 'validation/shared-lut/pretransforms-scan.json').read_text())
    src = SRC / TABLE
    assert src.exists(), f'{TABLE} not baked — run validation/shared-lut/bake-shared-scan.py'
    shutil.copyfile(src, DST / TABLE)
    table = b.read_png(DST / TABLE, SIZE)
    digest = fnv1a32(table.astype('<f4').tobytes())
    W = {}
    for sid, film in FILMS.items():
        if film == REF_FILM:
            continue
        entry = fits.get(film)
        assert entry and entry.get('reference_film') == REF_FILM and entry.get('features') == 'cubic20', \
            f'missing cubic20 W fit: {film} — run validation/shared-lut fit (ref={REF_FILM})'
        r = entry['residual_255']
        assert r['p99'] <= 3.0, (film, 'fit residual too large', r)
        assert len(entry['W']) == 3 and len(entry['W'][0]) == 20, (film, 'W must be 3x20 cubic')
        W[sid] = [round(x, 6) for row in entry['W'] for x in row]  # 3x20 行主序摊平
    scans = {'direct_scan': {'size': SIZE, 'asset': f'./styles/luts/{TABLE}', 'hash': digest,
                             'refFilm': REF_FILM, 'features': 'cubic20',
                             'styles': sorted(FILMS), 'W': W}}
    OUT.write_text('/* Generated by scripts/build-shared-scans.py; CC BY-SA 4.0. See NOTICE.md. */\n'
                   'window.FILMIFY_SCANS=' + json.dumps(scans, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'direct_scan size {SIZE}  {TABLE}  hash {digest}  W:{len(W)}')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
