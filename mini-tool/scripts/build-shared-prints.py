#!/usr/bin/env python3
"""Promote shared-domain print LUTs into styles/ and generate presets-prints.js.

架构（docs/shared-lut-design.md）：印相载体一张全局密度域
[-0.45, 3.55] 3D 表（基准胶卷恒等），其余胶卷经 3x10 二次预变换 W 映射进表。
运行时 mobile-film.js 用 style.preW + 全局常量替代逐组合 densityLow/Span 坐标。

本脚本：
1. 把选定尺寸的 print-<paper>-<size>.png 从 validation/shared-lut/luts/ 复制进
   styles/luts/（2393 选型史：41³ p99 5.01/4.56 超门、49³ 4.13 微超、57³ 3.17 过；
   2026-09-22 下午复测 53³ worst p99 2.57 与 57³ 同档，换 53³ 省 ~115KB——见 SIZE 表）。
2. 从 validation/shared-lut/pretransforms.json 取上线矩阵的 W
   （14 款彩负 × 8 款彩色印相载体，加 doublex×2302），
   键=style id，基准胶卷省略（恒等）。
3. 按 stamp-mobile-lut-hashes.py 同款口径（解码值 float32 LE 的 FNV-1a）打 hash。
"""
import importlib, json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
b = importlib.import_module('bake-film-stocks')
sys.path.insert(0, str(ROOT / 'validation' / 'shared-lut'))
bf = importlib.import_module('batch-fit')

SRC = ROOT / 'validation/shared-lut/luts'
DST = ROOT / 'styles/luts'
OUT = ROOT / 'styles/presets-prints.js'

# 每纸出厂尺寸（A/B 门禁 mae<=1.0 p99<=4.0 max<=12 全过；2393 是唯一 41^3 不过的，
# 53³ 五款 ECN-2 全过且 worst p99 2.57 优于 57³ 的 3.17）
SIZE = {'kodak_2393': 53}
DEFAULT_SIZE = 41

# 上线矩阵：14 款彩色负片 × 8 款彩色印相载体
# 全组合（W 拟合本来就是全量做的，不再卡工艺族）；2302 黑白印片仅 doublex，
# 反转片直扫不在此表。
ALLNEG = ['portrait', 'gold', 'ektar', 'ultramax', 'pro400h', 'superia',
          'portra160', 'portra800', 'c200',
          'vision250d', 'v3500t', 'vision50d', 'vision200t', 'verita200d']  # style id
PAPER_FILMS = {
    'kodak_portra_endura': ALLNEG, 'kodak_endura_premier': ALLNEG, 'kodak_supra_endura': ALLNEG,
    'kodak_ultra_endura': ALLNEG, 'kodak_ektacolor_edge': ALLNEG,
    'fujifilm_crystal_archive_typeii': ALLNEG,
    'kodak_2383': ALLNEG, 'kodak_2393': ALLNEG,
    'kodak_2302': ['doublex'],
}
STYLE2FILM = {k: v[0] for k, v in b.PROFILES.items()}


def fnv1a32(data: bytes) -> int:
    h = 0x811C9DC5
    for byte in data:
        h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    fits = json.loads((ROOT / 'validation/shared-lut/pretransforms.json').read_text())
    prints = {}
    for paper, styles in PAPER_FILMS.items():
        size = SIZE.get(paper, DEFAULT_SIZE)
        name = f'print-{paper}-{size}.png'
        src = SRC / name
        assert src.exists(), f'{name} not baked — run scripts/bake-shared-print.py'
        shutil.copyfile(src, DST / name)
        table = b.read_png(DST / name, size)
        digest = fnv1a32(table.astype('<f4').tobytes())
        W = {}
        for sid in styles:
            film = STYLE2FILM[sid]
            if paper == 'kodak_2302':
                continue  # 黑白印片：mono 表 R 轴渐变，恒等
            if film == bf.REF_FILM[paper]:
                continue  # 基准胶卷恒等
            entry = next((f for f in (fits.get(film) or {}).get('fits', []) if f['paper'] == paper), None)
            assert entry, f'missing W fit: {film} x {paper} — run validation/shared-lut/batch-fit.py'
            r = entry['residual_255']
            assert r['p99'] <= 3.0, (film, paper, 'fit residual too large', r)
            W[sid] = [round(x, 6) for row in entry['W'] for x in row]  # 3x10 行主序摊平
        prints[paper] = {'size': size, 'asset': f'./styles/luts/{name}', 'hash': digest,
                         'refFilm': bf.REF_FILM.get(paper, 'kodak_doublex'), 'mono': paper == 'kodak_2302', 'W': W}
        print(f'{paper:<34} size {size:2}  {name:44} hash {digest}  W:{len(W)}')
    OUT.write_text('/* Generated by scripts/build-shared-prints.py; CC BY-SA 4.0. See NOTICE.md. */\n'
                   'window.FILMIFY_PRINTS=' + json.dumps(prints, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
